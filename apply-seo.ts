async function applySEO() {
  const productsPath = path.join(__dirname, 'yandexProducts.json');
  try {
    const data = await fs.readFile(productsPath, 'utf-8');
    const products = JSON.parse(data);
    
    let updatedCount = 0;
    for (const p of products) {
      if (seoData[p.id]) {
        p.description = seoData[p.id].description;
        p.longDescription = seoData[p.id].longDescription;
        updatedCount++;
      }
    }
    
    await fs.writeFile(productsPath, JSON.stringify(products, null, 2), 'utf-8');
    console.log(`Успешно обновлено SEO для ${updatedCount} товаров.`);
  } catch (error) {
    console.error('Ошибка:', error);
  }
}

applySEO();
